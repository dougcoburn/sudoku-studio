function unrankPerm(n, k) {
  const items = Array.from({ length: k }, (_, i) => i);
  const out = [];
  for (let left = k; left >= 1; left--) {
    const f = FACT[left - 1];
    const idx = Number(n.v / f);
    n.v = n.v % f;
    out.push(items.splice(idx % items.length, 1)[0]);
  }
  return out;
}

function boxOf(r, c) {
  return Math.floor(r / 3) * 3 + Math.floor(c / 3);
}

function usedAt(grid, r, c) {
  let mask = 0;
  for (let i = 0; i < 9; i++) {
    if (grid[r][i]) mask |= 1 << grid[r][i];
    if (grid[i][c]) mask |= 1 << grid[i][c];
  }
  const br = Math.floor(r / 3) * 3;
  const bc = Math.floor(c / 3) * 3;
  for (let i = 0; i < 3; i++)
    for (let j = 0; j < 3; j++) {
      const d = grid[br + i][bc + j];
      if (d) mask |= 1 << d;
    }
  return mask;
}

function legalDigits(grid, r, c) {
  const used = usedAt(grid, r, c);
  const out = [];
  for (let d = 1; d <= 9; d++) if ((used & (1 << d)) === 0) out.push(d);
  return out;
}

function fillRows(grid, n) {
  const cells = [];
  for (let r = 3; r < 9; r++) for (let c = 0; c < 9; c++) cells.push([r, c]);

  function rec(i) {
    if (i === cells.length) return true;
    const [r, c] = cells[i];
    const legal = legalDigits(grid, r, c);
    if (legal.length === 0) return false;
    const k = BigInt(legal.length);
    const pick = Number(n.v % k);
    n.v = n.v / k;
    for (let off = 0; off < legal.length; off++) {
      const d = legal[(pick + off) % legal.length];
      grid[r][c] = d;
      if (rec(i + 1)) return true;
      grid[r][c] = 0;
    }
    return false;
  }
  return rec(0);
}

function applySymmetry(grid, n) {
  const transpose = Number(n.v % 2n) === 1;
  n.v = n.v / 2n;
  const colInStack = [unrankPerm(n, 3), unrankPerm(n, 3), unrankPerm(n, 3)];
  const stacks = unrankPerm(n, 3);
  const rowInBand = [unrankPerm(n, 3), unrankPerm(n, 3), unrankPerm(n, 3)];
  const bands = unrankPerm(n, 3);
  const digits = unrankPerm(n, 9); // 0..8 -> digit 1..9 maps from old digit-1

  const colOf = new Array(9);
  for (let s = 0; s < 3; s++)
    for (let k = 0; k < 3; k++) colOf[s * 3 + k] = stacks[s] * 3 + colInStack[s][k];

  const rowOf = new Array(9);
  for (let b = 0; b < 3; b++)
    for (let k = 0; k < 3; k++) rowOf[b * 3 + k] = bands[b] * 3 + rowInBand[b][k];

  const mapD = (d) => digits[d - 1] + 1;

  const out = Array.from({ length: 9 }, () => Array(9).fill(0));
  for (let r = 0; r < 9; r++) {
    for (let c = 0; c < 9; c++) {
      const d = mapD(grid[r][c]);
      const nr = rowOf[r];
      const nc = colOf[c];
      if (transpose) out[nc][nr] = d;
      else out[nr][nc] = d;
    }
  }
  return out;
}

function gridToString(grid) {
  let s = "";
  for (let r = 0; r < 9; r++) for (let c = 0; c < 9; c++) s += String(grid[r][c]);
  return s;
}

/** 81-char completed Sudoku. Same n always yields the same string. */
function generateSudoku(n) {
  if (n < 0n) n = -n;
  const bandIndex = Number(n % BAND_COUNT);
  n = n / BAND_COUNT;
  const band = BANDS[bandIndex];
  const grid = Array.from({ length: 9 }, () => Array(9).fill(0));
  for (let r = 0; r < 3; r++)
    for (let c = 0; c < 9; c++) grid[r][c] = band.charCodeAt(r * 9 + c) - 48;

  const token = { v: n };
  if (!fillRows(grid, token)) {
    throw new Error(`band ${bandIndex} failed to complete`);
  }
  const shuffled = applySymmetry(grid, token);
  return gridToString(shuffled);
}

function isValidComplete(s) {
  if (!/^[1-9]{81}$/.test(s)) return false;
  const g = [];
  for (let r = 0; r < 9; r++) {
    g.push([]);
    for (let c = 0; c < 9; c++) g[r][c] = s.charCodeAt(r * 9 + c) - 48;
  }
  const full = 0b1111111110;
  for (let i = 0; i < 9; i++) {
    let row = 0, col = 0, box = 0;
    for (let j = 0; j < 9; j++) {
      row |= 1 << g[i][j];
      col |= 1 << g[j][i];
      box |= 1 << g[Math.floor(i / 3) * 3 + Math.floor(j / 3)][(i % 3) * 3 + (j % 3)];
    }
    if (row !== full || col !== full || box !== full) return false;
  }
  return true;
}


